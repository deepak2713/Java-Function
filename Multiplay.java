public class Multiplay {

    public static int multiplay(int a, int b){
        int product= a*b;
        return product;
    }
    public static void main(String args[]){
        int a=5;
        int b=10;
        int prod= multiplay(a, b);
        System.out.println("the multiplay of a*b is: "+prod);
        

    }
}
